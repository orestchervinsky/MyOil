import { build } from 'esbuild'
import { writeFileSync } from 'fs'

// The Supabase dashboard editor doesn't bundle relative imports across files,
// so each function must ship as a single index.ts. This inlines _shared/telegram.ts
// into each function's src.ts, keeping one source of truth for the verification
// logic instead of hand-copying it into every function.

const functions = ['telegram-auth', 'game-action']

for (const fn of functions) {
  const result = await build({
    entryPoints: [`supabase/functions/${fn}/src.ts`],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    write: false,
    external: ['npm:@supabase/supabase-js@2'],
    banner: {
      js: '// AUTO-GENERATED by `npm run bundle:functions` — do not edit directly.\n// Edit src.ts (or ../_shared/telegram.ts) instead, then re-run the bundler.\n',
    },
  })
  const outPath = `supabase/functions/${fn}/index.ts`
  writeFileSync(outPath, result.outputFiles[0].text)
  console.log('bundled', outPath)
}
